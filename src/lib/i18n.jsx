const LanguageContext = createContext(null);

export function LanguageProvider({ children }) {
  const [lang, setLang] = useState("en");
  const [ready, setReady] = useState(false);

  useEffect(() => {
    try {
      const saved = window.localStorage.getItem("xmadrl.lang");
      if (saved === "ta" || saved === "en") setLang(saved);
    } catch {
      /* storage unavailable */
    }
    setReady(true);
  }, []);

  useEffect(() => {
    if (!ready) return;
    try {
      window.localStorage.setItem("xmadrl.lang", lang);
    } catch {
      /* storage unavailable */
    }
    document.documentElement.lang = lang;
  }, [lang, ready]);

  const value = {
    lang,
    setLang,
    t: (key) => DICT[lang]?.[key] ?? DICT.en[key] ?? key,
  };

  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

export function useLanguage() {
  const ctx = useContext(LanguageContext);
  return ctx ?? { lang: "en", setLang: () => {}, t: (key) => DICT.en[key] ?? key };
}